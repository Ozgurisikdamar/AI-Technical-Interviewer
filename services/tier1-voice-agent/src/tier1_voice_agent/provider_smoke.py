"""Opt-in live-provider smoke test (ADR-021). Never part of ``make test``.

Run it with ``make provider-smoke`` (OPENAI_API_KEY plus the ATI_OPENAI_* settings). It checks, for the
configured models:

1. Each model exists for this key (``GET /v1/models/{id}``).
2. A Realtime session set up like the interviewer accepts the pinned instructions and the one tool.
   The synthetic candidate turns are:
   - "finished": exactly one ``mark_answer_complete`` call;
   - "inject_score", "inject_tool", "inject_skip": no tool call and no output-monitor flag.
3. Synthetic speech (generated by a TTS model, in English and Turkish) is transcribed by the configured
   transcription model inside a Realtime session. The test records the transcription latency and a
   word-overlap score.

It measures connection time, time to the first response event, and time to ``response.done``
(p50, p95, p99 over the runs).

The evidence file (``docs/status/evidence/provider-smoke-<date>.json``) holds model IDs, request,
session and response IDs, counts, scores and latencies. It never holds the key, prompts, transcripts
or audio. Without a key the harness prints BLOCKED and exits 2, so it cannot be mistaken for a pass.

This module has not run against the live provider: no key is available in the repository. Its
first real run is also the first test of its own protocol handling.
"""

